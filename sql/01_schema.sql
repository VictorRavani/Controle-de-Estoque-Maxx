-- 01_schema.sql

-- CLIENTES
CREATE TABLE IF NOT EXISTS public.clientes (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nome character varying(100),
    codigo character varying(50),
    visibilidade boolean DEFAULT true
);

-- MATERIAL
CREATE TABLE IF NOT EXISTS public.material (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    codigo character varying(30) NOT NULL,
    descricao character varying(150) NOT NULL
);

-- OPERADOR
CREATE TABLE IF NOT EXISTS public.operador (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nome character varying,
    codigo bigint,
    visibilidade boolean DEFAULT true
);

-- PROCESSOS
CREATE TABLE IF NOT EXISTS public.processos (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nome character varying(100) NOT NULL
);

-- STATUS
CREATE TABLE IF NOT EXISTS public.status (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nome character varying(50) NOT NULL
);

-- TRATAMENTOS
CREATE TABLE IF NOT EXISTS public.tratamentos (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nome character varying(100) NOT NULL
);

-- PRODUTOS
CREATE TABLE IF NOT EXISTS public.produtos (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nome character varying NOT NULL,
    codigo character varying(50),
    saldo numeric(12,2) DEFAULT 0 NOT NULL,
    ativo boolean DEFAULT true NOT NULL,
    estoque_minimo numeric(12,2) DEFAULT 0 NOT NULL,
    localizacao character varying(100)
);

-- FORNECEDORES
CREATE TABLE IF NOT EXISTS public.fornecedores (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nome character varying(150) NOT NULL,
    whatsapp character varying(50),
    email character varying(120),
    forma_pagamento character varying(100),
    chave_pix character varying(150),
    ativo boolean DEFAULT true NOT NULL
);

-- VALOR DE COMPRA (Histórico de Preços por Fornecedor)
CREATE TABLE IF NOT EXISTS public.valor_de_compra (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_produto bigint NOT NULL REFERENCES public.produtos(id),
    id_fornecedor bigint NOT NULL REFERENCES public.fornecedores(id),
    preco_ultima_compra numeric(12,2) NOT NULL,
    data_modificacao timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- USUARIOS
CREATE TABLE IF NOT EXISTS public.usuarios (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    setor character varying,
    senha character varying NOT NULL,
    usuario character varying UNIQUE NOT NULL,
    privilegio bigint DEFAULT 1 NOT NULL,
    visibilidade boolean DEFAULT true NOT NULL,
    precisa_trocar_senha boolean DEFAULT false NOT NULL
);

-- MAQUINA
CREATE TABLE IF NOT EXISTS public.maquina (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    bancada character varying(100),
    setor character varying(100),
    empresa character varying(100)
);

-- ORDEM DE PRODUÇÃO
CREATE TABLE IF NOT EXISTS public.ordem_de_producao (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    numero_op character varying(255),
    quantidade double precision,
    id_produto bigint,
    data_entrega date,
    id_material integer,
    numero_qualidade character varying(50),
    id_tratamento bigint,
    id_cliente integer,
    data_criacao timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    status_id integer DEFAULT 1,
    ultimo_processo integer DEFAULT 0,
    processo_atual integer,
    CONSTRAINT fk_produto FOREIGN KEY (id_produto) REFERENCES public.produtos(id),
    CONSTRAINT fk_material FOREIGN KEY (id_material) REFERENCES public.material(id),
    CONSTRAINT fk_status FOREIGN KEY (status_id) REFERENCES public.status(id)
);

-- PRODUÇÃO
CREATE TABLE IF NOT EXISTS public.producao (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    dt_inicio timestamp without time zone,
    dt_fim timestamp without time zone,
    status integer,
    qtde_produzida bigint,
    id_operador integer,
    id_ordem_de_producao bigint,
    id_processo bigint NOT NULL,
    id_operador_fim integer,
    CONSTRAINT fk_ordem FOREIGN KEY (id_ordem_de_producao) REFERENCES public.ordem_de_producao(id),
    CONSTRAINT fk_processo FOREIGN KEY (id_processo) REFERENCES public.processos(id)
);

-- MOVIMENTAÇÕES DE ESTOQUE (Log Imutável: 0=Entrada, 1=Saída, 2=Ajuste)
CREATE TABLE IF NOT EXISTS public.movimentacoes_estoque (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_produto integer NOT NULL,
    operacao smallint NOT NULL,
    quantidade numeric(10,2) NOT NULL,
    saldo_anterior numeric(12,2),
    saldo_posterior numeric(12,2),
    observacao character varying(255),
    id_usuario integer NOT NULL,
    data timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT movimentacoes_estoque_operacao_check CHECK ((operacao = ANY (ARRAY[0, 1, 2]))),
    CONSTRAINT movimentacoes_estoque_quantidade_check CHECK ((quantidade > (0)::numeric)),
    CONSTRAINT fk_produto_mov FOREIGN KEY (id_produto) REFERENCES public.produtos(id)
);

-- TRIGGER PARA GARANTIR IMUTABILIDADE DO LOG DE MOVIMENTAÇÕES
CREATE OR REPLACE FUNCTION public.bloquear_alteracao_movimentacoes()
RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Operação negada: O histórico de movimentações de estoque é um log de auditoria imutável.';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_movimentacoes_imutavel ON public.movimentacoes_estoque;
CREATE TRIGGER trg_movimentacoes_imutavel
BEFORE UPDATE OR DELETE ON public.movimentacoes_estoque
FOR EACH ROW EXECUTE FUNCTION public.bloquear_alteracao_movimentacoes();
